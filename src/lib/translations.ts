export function translate(language: Language, message: string, values: Record<string, string | number> = {}): string {
  if (!message) return "";
  let result = language === "ar" ? (arabic[message] ?? "حدث خطأ غير متوقع. يرجى المحاولة مرة أخرى.") : message;
  for (const [key, value] of Object.entries(values)) result = result.replace(`{${key}}`, String(value));
  return result;
}

export function getBookName(book: BibleBook, language: Language): string {
  return language === "ar" ? arabicBookNames[book.id] ?? book.name : book.name;
}
